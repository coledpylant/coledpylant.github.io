"""## Question 2

## CVaR Model Formulation

**Decision variables:**
- $x_j$: the weight (fraction of the portfolio) allocated to stock $j$.
- $\alpha$: the threshold loss value that separates "normal" days from the worst-case days (this is the Value-at-Risk).
- $u_k$: the excess loss on day $k$ beyond the threshold $\alpha$ (zero if day $k$ was not worse than $\alpha$).

**Objective function (minimize the CVaR):**

$$
Z = \min_{x, \alpha, u} \left[ \alpha + \frac{1}{(1-\beta)q}\sum_{k=1}^{q} u_k \right]
$$

**Constraints:**

$$
\sum_j x_j = 1
$$

$$
x_j \geq 0 \quad \forall j
$$

$$
x^T \bar{y} \geq R
$$

$$
u_k \geq -x^T y_k - \alpha \quad \forall k
$$

$$
u_k \geq 0 \quad \forall k
$$
"""

# Create the Gurobi optimization model for the CVaR portfolio problem
profMod=gp.Model("CVaR_Portfolio")

# Number of stocks (columns) and number of days (rows) in the returns data
n = returns_2025.shape[1]  # number of stocks
q = returns_2025.shape[0]  # number of days

# Decision variable x_j: weight of each stock in the portfolio (must be >= 0)
x=profMod.addVars(n, lb=0, name="x")

# Decision variable u_k: excess loss on day k beyond the threshold alpha (must be >= 0)
u=profMod.addVars(q, lb=0, name="u")

# Decision variable alpha: the VaR threshold (can be positive or negative, so no lower bound)
alpha=profMod.addVar(lb=-GRB.INFINITY, name="alpha")

# Confidence level for the CVaR (beta = 0.95 means we focus on the worst 5% of days)
beta=0.95

# Objective function: minimize alpha + the average excess loss over the worst days
profMod.setObjective(
    alpha + (1 / ((1 - beta) * q)) * gp.quicksum(u[k] for k in range(q)),
    GRB.MINIMIZE
)

# Minimum required average daily return (R = 0.02%)
R=0.0002

# Mean return of each stock, calculated from the 2025 daily returns
mean_returns=returns_2025.mean().values

# Constraint 1: portfolio weights must sum to 1 (fully invested)
profMod.addConstr(gp.quicksum(x[j] for j in range(n)) == 1, name="budget")

# Constraint 2: the portfolio's expected return must be at least R
profMod.addConstr(
    gp.quicksum(x[j] * mean_returns[j] for j in range(n)) >= R,
    name="min_return"
)

# Constraint 3: link u_k to the portfolio's loss on day k (the "dam" constraint)
# Convert returns to a plain array so we can index it by day (k) and stock (j)
returns_array = returns_2025.values

for k in range(q):
    portfolio_loss_k = -gp.quicksum(x[j] * returns_array[k, j] for j in range(n))
    profMod.addConstr(u[k] >= portfolio_loss_k - alpha, name=f"cvar_link_{k}")

# x_j >= 0 and u_k >= 0 were already set when we created those variables
# with lb=0, so no additional constraints are needed for those.

# Silence Gurobi's solver log (must be set BEFORE optimize())
profMod.Params.OutputFlag = 0

# Solve the optimization model
profMod.optimize()

if profMod.Status != GRB.OPTIMAL:
    raise RuntimeError(f"Question 2 optimization did not solve to optimality. Gurobi status: {profMod.Status}")

# Print the optimal CVaR (objective value) and the VaR (alpha)
print(f"Optimal CVaR (Z): {profMod.ObjVal:.6f}")
print(f"VaR (alpha): {alpha.X:.6f}")

