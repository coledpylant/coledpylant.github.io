# Part 4: Minimize the maximum monthly CVaR

def optimize_max_monthly_cvar(returns, beta_value=0.95, R_value=0.0002):

    # Number of stocks
    n_local = returns.shape[1]

    # Create optimization model
    model = gp.Model("Max_Monthly_CVaR")
    model.Params.OutputFlag = 0


    # Decision variables
    # Portfolio weights
    x_local = model.addVars(n_local, lb=0, name="x")

    # One alpha (VaR threshold) for each month
    months = returns.index.to_period("M").unique()

    alpha_local = model.addVars(
        len(months),
        lb=-GRB.INFINITY,
        name="alpha"
    )

    # One maximum-CVaR variable
    max_cvar = model.addVar(
        lb=-GRB.INFINITY,
        name="max_cvar"
    )

    # Objective
    # Minimize the worst monthly CVaR
    model.setObjective(max_cvar, GRB.MINIMIZE)

    # Portfolio constraints
    # Portfolio must be fully invested
    model.addConstr(
        gp.quicksum(x_local[j] for j in range(n_local)) == 1
    )

    # Minimum expected return constraint
    mean_returns_local = returns.mean().values

    model.addConstr(
        gp.quicksum(
            x_local[j] * mean_returns_local[j]
            for j in range(n_local)
        ) >= R_value
    )


    # Monthly CVaR constraints
    # Go through each month separately
    for m, month in enumerate(months):

        # Get the returns belonging to this month
        month_returns = returns[
            returns.index.to_period("M") == month
        ]

        month_array = month_returns.values
        q_month = month_returns.shape[0]

        # Excess-loss variables for the trading days
        # in this particular month
        u_month = model.addVars(
            q_month,
            lb=0,
            name=f"u_{m}"
        )

        # CVaR constraints for every trading day in the month
        for k in range(q_month):

            portfolio_loss = -gp.quicksum(
                x_local[j] * month_array[k, j]
                for j in range(n_local)
            )

            model.addConstr(
                u_month[k] >= portfolio_loss - alpha_local[m]
            )

        # Calculate this month's CVaR
        monthly_cvar = (
            alpha_local[m]
            +
            (1 / ((1 - beta_value) * q_month))
            * gp.quicksum(
                u_month[k] for k in range(q_month)
            )
        )

        # max_cvar must be at least as large
        # as the CVaR of this month
        model.addConstr(
            max_cvar >= monthly_cvar
        )

    model.optimize()

    if model.Status != GRB.OPTIMAL:
        raise RuntimeError(
            f"Maximum monthly CVaR optimization did not solve to optimality. "
            f"Gurobi status: {model.Status}"
        )

    weights = pd.Series(
        [x_local[j].X for j in range(n_local)],
        index=returns.columns
    )

    return weights, model.ObjVal

