# Reusable CVaR optimization function
# This allows us to test different beta values without changing the original Question 2 model.

def optimize_cvar_portfolio(returns, beta_value, R_value=0.0002):

    # Number of stocks and trading days
    n_local = returns.shape[1]
    q_local = returns.shape[0]

    # Create optimization model
    model = gp.Model(f"CVaR_beta_{beta_value}")
    model.Params.OutputFlag = 0

    # Decision variables
    x_local = model.addVars(n_local, lb=0, name="x")
    u_local = model.addVars(q_local, lb=0, name="u")
    alpha_local = model.addVar(lb=-GRB.INFINITY, name="alpha")

    # Objective: minimize CVaR
    model.setObjective(
        alpha_local +
        (1 / ((1 - beta_value) * q_local)) *
        gp.quicksum(u_local[k] for k in range(q_local)),
        GRB.MINIMIZE
    )

    # Portfolio must be fully invested
    model.addConstr(
        gp.quicksum(x_local[j] for j in range(n_local)) == 1
    )

    # Minimum expected return constraint
    mean_returns_local = returns.mean().values

    model.addConstr(
        gp.quicksum(
            x_local[j] * mean_returns_local[j]
            for j in range(n_local)
        ) >= R_value
    )

    # CVaR constraints
    returns_array_local = returns.values

    for k in range(q_local):
        portfolio_loss = -gp.quicksum(
            x_local[j] * returns_array_local[k, j]
            for j in range(n_local)
        )

        model.addConstr(
            u_local[k] >= portfolio_loss - alpha_local
        )

    # Solve model
    model.optimize()

    if model.Status != GRB.OPTIMAL:
        raise RuntimeError(
            f"CVaR optimization did not solve to optimality. Gurobi status: {model.Status}"
        )

    # Save portfolio weights
    weights = pd.Series(
        [x_local[j].X for j in range(n_local)],
        index=returns.columns
    )

    return weights, model.ObjVal, alpha_local.X

