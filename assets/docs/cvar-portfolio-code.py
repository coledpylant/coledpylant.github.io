# ============================================================
# Reusable CVaR evaluator for a FIXED set of portfolio weights
# ------------------------------------------------------------
# For a given portfolio x, the project's CVaR formula minimizes over alpha.
# Therefore, out-of-sample evaluation keeps the portfolio weights fixed but
# re-solves alpha for the new return sample.
# ============================================================

def cvar_of_return_series(return_series, beta_value):
    """Calculate CVaR and VaR for a fixed stream of returns."""
    q_local = len(return_series)

    if q_local == 0:
        raise ValueError("Cannot calculate CVaR from an empty return series.")

    losses = -np.asarray(return_series).flatten()

    model = gp.Model("CVaR_eval")
    model.Params.OutputFlag = 0

    alpha_var = model.addVar(lb=-GRB.INFINITY, name="alpha")
    u_var = model.addVars(q_local, lb=0, name="u")

    model.setObjective(
        alpha_var
        + (1 / ((1 - beta_value) * q_local))
        * gp.quicksum(u_var[k] for k in range(q_local)),
        GRB.MINIMIZE
    )

    for k in range(q_local):
        model.addConstr(u_var[k] >= losses[k] - alpha_var)

    model.optimize()

    if model.Status != GRB.OPTIMAL:
        raise RuntimeError(
            f"CVaR evaluation did not solve to optimality. Gurobi status: {model.Status}"
        )

    return model.ObjVal, alpha_var.X


def evaluate_fixed_portfolio_cvar(weights, returns_df, beta_value):
    """Evaluate already-selected portfolio weights on a new return sample."""
    common = weights.index.intersection(returns_df.columns)
    w = weights[common]
    coverage = w.sum()

    if coverage <= 0:
        raise ValueError(
            "None of the weighted stocks have data in this sample. "
            "Check that the ticker universe lines up between periods."
        )

    # This should not normally be needed because the eligible universe is
    # defined consistently above, but it keeps the evaluator robust if a
    # weighted ticker is unavailable in a later sample.
    if not np.isclose(coverage, 1.0, atol=1e-6):
        missing = weights[weights > 0].index.difference(common)
        print(
            f"WARNING: only {coverage:.4f} of the portfolio's weight is present "
            f"in this sample ({len(missing)} stock(s) missing: {list(missing)}); "
            "renormalizing so the evaluated portfolio remains fully invested."
        )
        w = w / coverage

    portfolio_returns = returns_df[common].values @ w.values
    return cvar_of_return_series(portfolio_returns, beta_value)

